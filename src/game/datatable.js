const System = globalThis;


//==============================================================================
// 데이터 테이블 로더.
//
// 카드·대전 설정 같은 게임 데이터 테이블(JSON)을 번들에 인라인하지 않고
// 런타임에 fetch 로 로드한다. cache: "no-cache" 로 서버와 재검증하므로
// 배포 후 브라우저가 옛 테이블을 계속 쓰는 문제를 막는다.
//==============================================================================


//==============================================================================
// 데이터 테이블 로드. 실패 시 null 반환.
//==============================================================================
/**
 * @param { string } url
 * @returns { Promise<object> }
 */
export async function loadDataTable(url) {
	try {
		const response = await System.window.fetch(url, { cache: "no-cache" });
		if (!response.ok) {
			return null;
		}
		const table = await response.json();
		return table;
	}
	catch (error) {
		console.error(error);
		return null;
	}
}
